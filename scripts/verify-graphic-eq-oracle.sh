#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${TMPDIR:-/tmp}/audacity-graphic-eq-oracle"
SOURCE="$ROOT/scripts/graphic-eq-oracle.cpp"
FIXTURE="$ROOT/src/lib/graphicEqOracle.fixture.bin"
mkdir -p "$WORK"
BINARY="$WORK/oracle"
if [[ ! -x "$BINARY" || "$SOURCE" -nt "$BINARY" ]]; then
  g++ -std=c++17 -O2 -ffp-contract=off "$SOURCE" -o "$BINARY"
fi
"$BINARY" "$WORK/fixture.bin"
cmp "$WORK/fixture.bin" "$FIXTURE"
printf 'Graphic EQ frozen oracle fixture matches independently regenerated bytes\n'
