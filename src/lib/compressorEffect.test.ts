import {
  createCompressorState,
  DEFAULT_COMPRESSOR_SETTINGS,
  evaluateCompressorTransferFunction,
  getMaxCompressorCompressionDb,
  isCompressorBypassed,
  processCompressorChannels,
  processCompressorStream,
  validateCompressorSettings,
  type CompressorSettings,
} from './compressorEffect';

function expectSamples(actual: Float32Array, expected: readonly number[], precision = 5): void {
  expect(actual.length).toBe(expected.length);
  for (let index = 0; index < expected.length; index += 1) {
    expect(actual[index], `sample ${index}`).toBeCloseTo(expected[index], precision);
  }
}

const oracleInput = [
  new Float32Array([
    0, 0.1, -0.25, 0.5, -1, 0.75, -0.5, 0.25, 1, -0.75, 0.5, -0.25,
    0.125, -0.0625, 0.03125, -0.015625, 0.9, -0.8, 0.7, -0.6, 0.4, -0.3, 0.2, -0.1,
  ]),
  new Float32Array([
    0, -0.05, 0.2, -0.4, 0.8, -0.6, 0.4, -0.2, 0.6, -0.4, 0.2, -0.1,
    -0.125, 0.0625, -0.03125, 0.015625, -0.7, 0.6, -0.5, 0.4, -0.3, 0.2, -0.1, 0.05,
  ]),
];

describe('Audacity 4.0.2 CompressorProcessor parity', () => {
  it('matches the official C++ default stereo oracle with look-ahead compensation', () => {
    const originals = oracleInput.map((channel) => new Float32Array(channel));
    const actual = processCompressorChannels(oracleInput, { ...DEFAULT_COMPRESSOR_SETTINGS }, 1000);

    // Generated by the unmodified Audacity-4.0.2 CompressorProcessor.cpp,
    // GainReductionComputer.cpp and LookAheadGainReduction.cpp in /tmp oracle.
    expectSamples(actual[0], [
      0, 0.2818382978, -0.6147264838, 1.072639585, -1.87165463, 1.249213219,
      -0.8328653574, 0.4183493257, 1.444996238, -1.03783381, 0.6932137012,
      -0.3488385975, 0.1756436527, -0.0884321481, 0.04452028871, -0.02241176926,
      1.190931439, -1.024782896, 0.8968734145, -0.769805491, 0.5154358745,
      -0.3890320063, 0.2613454163, -0.1316759288,
    ]);
    expectSamples(actual[1], [
      0, -0.1409191489, 0.4917812049, -0.8581116796, 1.497323751, -0.999370575,
      0.6662923098, -0.3346794546, 0.8669977784, -0.5535113811, 0.2772854865,
      -0.139535442, -0.1756436527, 0.0884321481, -0.04452028871, 0.02241176926,
      -0.9262800217, 0.768587172, -0.6406238675, 0.5132036209, -0.3865769207,
      0.2593546808, -0.1306727082, 0.06583796442,
    ]);
    expect(oracleInput[0]).toEqual(originals[0]);
    expect(oracleInput[1]).toEqual(originals[1]);
  });

  it('matches the official C++ zero attack/release hard-knee mono oracle', () => {
    const settings: CompressorSettings = {
      thresholdDb: -20,
      makeupGainDb: 0,
      kneeWidthDb: 0,
      compressionRatio: 2,
      lookaheadMs: 0,
      attackMs: 0,
      releaseMs: 0,
    };
    const input = [new Float32Array([0, 0.01, -0.1, 0.5, -1, 0.25, -0.05, 0.75, -0.5, 0.125, 0.03125, -0.25])];
    const actual = processCompressorChannels(input, settings, 48000);
    expectSamples(actual[0], [
      0, 0.009999999776, -0.09987916052, 0.2231845558, -0.3156306744, 0.1578153074,
      -0.05000000075, 0.273794353, -0.2231845558, 0.1115922779, 0.03125, -0.1578153074,
    ]);
  });

  it('keeps streaming output invariant across arbitrary block boundaries and the 512-sample cap', () => {
    const input = [new Float32Array(1031), new Float32Array(1031)];
    for (let index = 0; index < 1031; index += 1) {
      input[0][index] = Math.sin(index * 0.17) * (index % 37 === 0 ? 1 : 0.35);
      input[1][index] = Math.cos(index * 0.11) * (index % 53 === 0 ? 0.9 : 0.2);
    }
    const whole = processCompressorStream(input, createCompressorState({ ...DEFAULT_COMPRESSOR_SETTINGS }, 44100, 2));
    const state = createCompressorState({ ...DEFAULT_COMPRESSOR_SETTINGS }, 44100, 2);
    const chunks = [
      processCompressorStream(input.map((channel) => channel.slice(0, 3)), state),
      processCompressorStream(input.map((channel) => channel.slice(3, 509)), state),
      processCompressorStream(input.map((channel) => channel.slice(509, 514)), state),
      processCompressorStream(input.map((channel) => channel.slice(514)), state),
    ];
    for (let channel = 0; channel < 2; channel += 1) {
      expectSamples(new Float32Array(chunks.flatMap((chunk) => Array.from(chunk[channel]))), Array.from(whole[channel]));
    }
  });

  it('removes initial look-ahead silence and flushes the delayed tail without changing length', () => {
    const input = [new Float32Array(16)];
    input[0][0] = 1;
    input[0][8] = -0.5;
    const actual = processCompressorChannels(input, { ...DEFAULT_COMPRESSOR_SETTINGS }, 1000);
    expect(actual[0].length).toBe(16);
    expect(actual[0][0]).not.toBe(0);
    expect(actual[0][8]).not.toBe(0);
    expect(Array.from(actual[0]).every(Number.isFinite)).toBe(true);
  });

  it('uses one linked stereo sidechain rather than independent channel compression', () => {
    const left = new Float32Array(oracleInput[0]);
    const rightOnly = [new Float32Array(oracleInput[0].length), new Float32Array(oracleInput[1])];
    const linked = processCompressorChannels([left, new Float32Array(oracleInput[1])], { ...DEFAULT_COMPRESSOR_SETTINGS }, 1000);
    const unlinkedRight = processCompressorChannels(rightOnly, { ...DEFAULT_COMPRESSOR_SETTINGS }, 1000);
    expect(linked[1]).not.toEqual(unlinkedRight[1]);
    for (let index = 0; index < left.length; index += 1) {
      if (left[index] !== 0 && oracleInput[1][index] !== 0) {
        expect(linked[1][index] / oracleInput[1][index]).toBeCloseTo(linked[0][index] / left[index], 4);
      }
    }
  });
});

describe('Compressor transfer function and validation', () => {
  it('implements hard and soft knees plus make-up gain and maximum compression', () => {
    const hard: CompressorSettings = { ...DEFAULT_COMPRESSOR_SETTINGS, thresholdDb: -20, kneeWidthDb: 0, compressionRatio: 2, makeupGainDb: 0 };
    expect(evaluateCompressorTransferFunction(hard, -30)).toBeCloseTo(-30, 6);
    expect(evaluateCompressorTransferFunction(hard, 0)).toBeCloseTo(-10, 6);
    expect(getMaxCompressorCompressionDb(hard)).toBeCloseTo(10, 6);

    const soft = { ...DEFAULT_COMPRESSOR_SETTINGS };
    expect(evaluateCompressorTransferFunction(soft, -20)).toBeCloseTo(-11, 6);
    expect(evaluateCompressorTransferFunction(soft, -12)).toBeCloseTo(-3.5625, 6);
    expect(getMaxCompressorCompressionDb(soft)).toBeCloseTo(9, 6);
  });

  it('recognizes Audacity bypass parameters', () => {
    expect(isCompressorBypassed({ ...DEFAULT_COMPRESSOR_SETTINGS, compressionRatio: 1, makeupGainDb: 0, lookaheadMs: 0 })).toBe(true);
    expect(isCompressorBypassed({ ...DEFAULT_COMPRESSOR_SETTINGS, compressionRatio: 1, makeupGainDb: 0 })).toBe(false);
    expect(isCompressorBypassed({ ...DEFAULT_COMPRESSOR_SETTINGS })).toBe(false);
  });

  it.each([
    ['thresholdDb', -61], ['thresholdDb', 1], ['makeupGainDb', 31], ['kneeWidthDb', -1],
    ['compressionRatio', 0.5], ['compressionRatio', 101], ['lookaheadMs', 101],
    ['attackMs', 201], ['releaseMs', 1001], ['releaseMs', Number.NaN],
  ])('rejects out-of-range %s values', (key, value) => {
    expect(() => validateCompressorSettings({ ...DEFAULT_COMPRESSOR_SETTINGS, [key]: value })).toThrow(RangeError);
  });

  it('rejects invalid channel layouts, sample rates and non-finite PCM', () => {
    expect(() => createCompressorState({ ...DEFAULT_COMPRESSOR_SETTINGS }, 0, 1)).toThrow(/采样率/);
    expect(() => createCompressorState({ ...DEFAULT_COMPRESSOR_SETTINGS }, 44100, 3)).toThrow(/单声道或立体声/);
    expect(() => processCompressorChannels([], { ...DEFAULT_COMPRESSOR_SETTINGS }, 44100)).toThrow(/单声道或立体声/);
    expect(() => processCompressorChannels([new Float32Array([Number.NaN])], { ...DEFAULT_COMPRESSOR_SETTINGS }, 44100)).toThrow(/非有限值/);
    expect(() => processCompressorChannels(
      [new Float32Array([3.4e38])],
      { ...DEFAULT_COMPRESSOR_SETTINGS, compressionRatio: 1, makeupGainDb: 30, lookaheadMs: 0 },
      44100,
    )).toThrow(/非有限输出/);
  });
});
